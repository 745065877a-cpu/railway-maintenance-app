# 5. 정비 도래 계산
# =========================================================

def check_maintenance_due(vehicle):

    info = vehicle_state[vehicle]

    current_hours = info["current_hours"]
    last_hours = info["last_maintenance_hours"]

    last_date = datetime.strptime(
        info["last_maintenance_date"],
        "%Y-%m-%d"
    )

    hours_since = current_hours - last_hours

    today = datetime.today()

    results = []

    for maintenance_type, rule in maintenance_rules.items():

        next_date = last_date + relativedelta(
            months=rule["months"]
        )

        hours_due = (
            hours_since >= rule["hours"]
        )

        date_due = (
            today >= next_date
        )

        hours_ratio = (
            hours_since / rule["hours"]
        )

        if hours_due or date_due:
            status = "정비대상"

        elif hours_ratio >= 0.8:
            status = "정비임박"

        else:
            status = "정상"

        results.append({
            "정비종류": maintenance_type,
            "정비구분": rule["구분"],
            "정비후가동시간": hours_since,
            "시간기준": rule["hours"],
            "기간기준도래일": next_date.strftime("%Y-%m-%d"),
            "판정": status
        })

    return results


# =========================================================
# 6. 최근 정비 이력
# =========================================================

def get_latest_maintenance(vehicle):

    vehicle_history = history_df[
        history_df["차량번호"] == vehicle
    ].copy()

    if vehicle_history.empty:
        return None

    vehicle_history["점검일"] = pd.to_datetime(
        vehicle_history["점검일"]
    )

    latest = vehicle_history.sort_values(
        "점검일",
        ascending=False
    ).iloc[0]

    return latest


